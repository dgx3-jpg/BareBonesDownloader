using System;
using System.Collections.Generic;
using System.IO;
using System.Threading.Tasks;
using System.Web.Script.Serialization;

namespace BareBonesDownloader
{
    internal static class MetadataLookupTests
    {
        private static int _checks;
        private static Dictionary<string, string> Empty() { return new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase); }
        private static void Check(bool value, string name) { if (!value) throw new Exception("FAIL: " + name); _checks++; Console.WriteLine("PASS: " + name); }
        private static int Main(string[] args)
        {
            try
            {
                if (args.Length > 0 && args[0] == "live")
                {
                    Dictionary<string, string> live = OnlineMetadata.Lookup("(Nice Dream)", "Radiohead", 233.2, delegate { return false; }, Console.WriteLine);
                    Console.WriteLine(new JavaScriptSerializer().Serialize(live));
                    if (!live.ContainsKey("album")) throw new Exception("No confident live catalogue album result.");
                    return 0;
                }
                Action<string> log = delegate { };
                Func<bool> running = delegate { return false; };
                Dictionary<string, string> source = Empty(); source["title"] = "Song"; source["artist"] = "Artist"; source["album"] = "Album";
                int calls = 0;
                MetadataLookup forbidden = delegate(string title, string artist, double? duration, Func<bool> stop, Action<string> report)
                { calls++; throw new Exception("Unexpected lookup"); };
                var complete = MusicMetadata.ResolveTags(source, Empty(), "filename", 180, forbidden, running, log);
                Check(calls == 0 && complete["album"] == "Album", "complete YouTube tags cause no online request");
                string info = Path.Combine(Path.GetTempPath(), "topic-" + Guid.NewGuid().ToString("N") + ".json");
                try
                {
                    File.WriteAllText(info, new JavaScriptSerializer().Serialize(new
                    { title = "曲名", description = "Provided to YouTube by Label\n\n曲名 · 作曲家\n\nアルバム\n\n℗ Label\n\nAuto-generated by YouTube." }));
                    var parsed = MusicMetadata.ExpectedTags(info);
                    Check(parsed["title"] == "曲名" && parsed["artist"] == "作曲家" && parsed["album"] == "アルバム", "Topic description supplies missing structured fields");
                    File.WriteAllText(info, new JavaScriptSerializer().Serialize(new
                    { title = "曲名", description = "Provided to YouTube by Label\n\n曲名 · 作曲家\n\n℗ Label\n\nAuto-generated by YouTube." }));
                    Check(!MusicMetadata.ExpectedTags(info).ContainsKey("album"), "copyright line is not treated as an album");
                }
                finally { File.Delete(info); }
                source.Remove("album");
                MetadataLookup matching = delegate(string title, string artist, double? duration, Func<bool> stop, Action<string> report)
                { calls++; var r = Empty(); r["title"] = "Other spelling"; r["artist"] = "Other spelling"; r["album"] = "Found album"; return r; };
                var filled = MusicMetadata.ResolveTags(source, Empty(), "filename", 180, matching, running, log);
                Check(filled["title"] == "Song" && filled["artist"] == "Artist" && filled["album"] == "Found album", "catalogue fills missing fields while preserving source tags");
                MetadataLookup unavailable = delegate { throw new IOException("offline"); };
                var offline = MusicMetadata.ResolveTags(source, Empty(), "filename", 180, unavailable, running, log);
                Check(offline["title"] == "Song" && !offline.ContainsKey("album"), "offline lookup keeps partial tags without failing");
                var untagged = MusicMetadata.ResolveTags(Empty(), Empty(), "filename", 180,
                    delegate { return Empty(); }, running, log);
                Check(untagged.Count == 0, "no confident match leaves unknown tags empty");
                var track = new CatalogueTrack { Title = "Song", Artist = "Artist", Album = "Album", Duration = 180 };
                var selected = OnlineMetadata.Select(new[] { track }, "Song", "Artist", 180);
                Check(selected["album"] == "Album", "matching song artist and duration are accepted");
                Check(OnlineMetadata.Select(new[] { track }, "Song (Live)", "Artist", 180).Count == 0, "studio recording does not tag a live version");
                Check(OnlineMetadata.Select(new[] { track }, "Song", "Cover artist", 180).Count == 0, "wrong performer is rejected");
                Check(OnlineMetadata.Select(new[] { track }, "Song", "Artist", 220).Count == 0, "wrong duration is rejected");
                var cover = new CatalogueTrack { Title = "Song", Artist = "Other artist", Album = "Other album", Duration = 180 };
                Check(OnlineMetadata.Select(new[] { track, cover }, "Song", null, 180).Count == 0, "ambiguous performer is rejected");
                var reissue = new CatalogueTrack { Title = "Song", Artist = "Artist", Album = "Other album", Duration = 180 };
                Check(!OnlineMetadata.Select(new[] { track, reissue }, "Song", "Artist", 180).ContainsKey("album"), "ambiguous album is left unknown");
                Check(OnlineMetadata.Select(new[] { track }, "Song", null, 180).ContainsKey("artist"), "unique title and duration can recover a missing artist");
                string response = new JavaScriptSerializer().Serialize(new { results = new[] { new
                { kind = "song", trackName = "Song", artistName = "Artist", collectionName = "Album", trackTimeMillis = 180000, releaseDate = "2026-10-31T00:00:00Z", trackNumber = 2 } } });
                Check(OnlineMetadata.Parse(response)[0].Date == "20261031", "catalogue response maps track and release metadata");
                int fetches = 0;
                var retried = OnlineMetadata.Lookup("Song", "Artist", 180, running, log,
                    delegate { fetches++; if (fetches == 1) throw new TaskCanceledException(); return response; });
                Check(fetches == 2 && retried["album"] == "Album", "catalogue timeout falls through to the other region");
                int regions = 0;
                string firstRegion = new JavaScriptSerializer().Serialize(new { results = new[] {
                    new { kind = "song", trackName = "Song", artistName = "Artist A", collectionName = "Album A", trackTimeMillis = 180000 },
                    new { kind = "song", trackName = "Song", artistName = "Artist A", collectionName = "Album B", trackTimeMillis = 180000 } } });
                string otherRegion = new JavaScriptSerializer().Serialize(new { results = new[] {
                    new { kind = "song", trackName = "Song", artistName = "Artist B", collectionName = "Album C", trackTimeMillis = 180000 } } });
                var conflict = OnlineMetadata.Lookup("Song", null, 180, running, log,
                    delegate { regions++; return regions == 1 ? firstRegion : otherRegion; });
                Check(conflict.Count == 0, "conflicting catalogue regions do not mix different performers");
                bool cancelled = false;
                try { MusicMetadata.ResolveTags(source, Empty(), "filename", 180,
                    delegate { throw new OperationCanceledException(); }, delegate { return true; }, log); }
                catch (OperationCanceledException) { cancelled = true; }
                Check(cancelled, "explicit user cancellation remains effective");
                Console.WriteLine("PASS: " + _checks + " metadata lookup checks");
                return 0;
            }
            catch (Exception ex) { Console.Error.WriteLine(ex); return 1; }
        }
    }
}
